def pick_photo(subject, photo):
    if photo and photo != "auto":
        return photo, "given"
    s = SUBJECTS[subject]
    # 1) the photo the user already chose for a card design
    for sj in glob.glob(PROJ + "/chris/card/save.json"):
        if os.path.exists(os.path.join(os.path.dirname(sj), "photo.jpg")):
            return os.path.join(os.path.dirname(sj), "photo.jpg"), "user's card pick (chris/card/save.json)"
    best, bs = None, -1
    for d in s["photo_dirs"]:
        for f in glob.glob(d + "/*.jpg"):
            if "preview" in f or "print" in f: continue
            im = Image.open(f).convert("L"); im.thumbnail((512, 512))
            sharp = ImageStat.Stat(im.filter(ImageFilter.FIND_EDGES)).var[0]
            score = sharp * (1.3 if im.height > im.width else 1.0)
            if score > bs: best, bs = f, score
    return best, "sharpest portrait-orientation photo"

def add_character(a):
    subj = a.from_subject.lower()
    if subj not in SUBJECTS: raise SystemExit("unknown subject " + subj)
    S = SUBJECTS[subj]; slug = S["slug"]
    d = os.path.join(ROOT, "characters", slug); os.makedirs(os.path.join(d, "art"), exist_ok=True)
    photo, why = pick_photo(subj, a.photo)
    print("photo:", photo, "(" + why + ")")
    prompts = {
     "style_lock": "characters/reptilian-ralph-middle-management/art/base.png",
     "likeness_ref": photo,
     "sheet": "Tall vertical 9:16 character portrait ... EXACTLY the same art style as the first reference image ... (see experiments/MANIFEST.md for the full prompt)",
     "blank_face": "Edit the reference image. Keep EVERYTHING identical ... remove both eyes, both eyebrows, and the mouth ...",
    }
    json.dump(prompts, open(os.path.join(d, "art", "prompts.json"), "w"), indent=1)
    if not os.path.exists(os.path.join(d, S["rig"]["art"]["base"])):
        raise SystemExit("art missing: generate art/base.png (blank-face plate) with the prompts in art/prompts.json, then rerun with --skip-art")
    rig = dict(S["rig"]); rig["voice_fallback"] = S["voice_fallback"]
    json.dump(rig, open(os.path.join(d, "rig.json"), "w"), indent=1)
    ch = dict(S["character"]); ch["voice"] = S["voice"]
    json.dump(ch, open(os.path.join(d, "character.json"), "w"), indent=1)
    words = sum(len(b["text"].split()) for b in S["delivery"])
    dl = {"beats": S["delivery"], "metadata": {"beat_count": len(S["delivery"]), "punchline_count": sum(b["type"] == "punchline" for b in S["delivery"]),
          "word_count": words}, "profile": ch["profile"], "version": "freaktown.delivery.v1", "voice": S["voice"]}
    json.dump(dl, open(os.path.join(d, "delivery.json"), "w"), indent=1)
    subprocess.run([sys.executable, os.path.join(ROOT, "pipeline", "prep_rig.py"), slug], check=True)
    h = lambda p: "sha256:" + hashlib.sha256(open(os.path.join(d, p), "rb").read()).hexdigest()
    meta = {"slug": slug, "status": "ready", "created_at": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
            "creator": "char-onboard-v0 (local experiment)", "voice": S["voice"]["provider"], "word_count": words, "beat_count": len(S["delivery"]),
            "source_photo": photo, "files": {p: h(p) for p in ("character.json", "delivery.json", "rig.json")},
            "lineage": {"relation": "portrait", "parent": None, "root": "dad", "depth": 1}}
    json.dump(meta, open(os.path.join(d, "meta.json"), "w"), indent=1)
    print("character ready:", d)
